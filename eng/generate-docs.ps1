<#
.SYNOPSIS
    Regenerates the committed API reference under docs/api/ from the XML documentation comments.

.DESCRIPTION
    The reference is generated by docfx directly from the source with Roslyn, so it resolves
    <inheritdoc/> (which the compiler-emitted XML documentation file does not) and it sees only the
    public and protected surface (docfx's default API filter), which keeps GDK.Net.Interop out.

    Metadata is produced from the net10.0 target framework only, and that is sufficient: the three
    targets export an identical public surface. The #if NET7_0_OR_GREATER guards select
    [UnmanagedCallersOnly] function pointers over Marshal.GetFunctionPointerForDelegate, but the
    types that differ are internal, so no public member exists only off net10.0. If that ever
    changes this reference would silently omit it -- see the TFM surface check in
    docs/architecture.md.

    Output is one markdown file per type plus one per namespace and a toc.yml, written to
    docs/api/. It is committed, so regenerate it in the same change as any public API edit.

    Requires the local docfx tool:

        dotnet tool restore

    It is resolved from the feeds in NuGet.config. See docs/building.md for the feed notes.

.PARAMETER Check
    Do not modify docs/api/. Generate into a temporary directory and report whether the committed
    output is up to date, exiting non-zero when it is not. Intended for CI.

.PARAMETER NoRestore
    Skip `dotnet tool restore`.
#>
[CmdletBinding()]
param(
    [switch] $Check,
    [switch] $NoRestore
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$repoRoot = Split-Path -Parent $PSScriptRoot
$config = Join-Path $PSScriptRoot 'docfx.json'
$committed = Join-Path $repoRoot 'docs\api'

function Get-GdkEdition {
    $props = Join-Path $repoRoot 'Directory.Build.props'
    $match = Select-String -Path $props -Pattern '<GdkEdition>(\d+)</GdkEdition>' | Select-Object -First 1
    if (-not $match) {
        throw "Could not read <GdkEdition> from $props."
    }
    return $match.Matches[0].Groups[1].Value
}

function Write-ApiIndex {
    param([Parameter(Mandatory)] [string] $Destination)

    $edition = Get-GdkEdition
    $pages = (Get-ChildItem $Destination -Filter '*.md' -File).Count

    # docfx's toc.yml lists the namespaces as its top-level entries.
    $toc = Join-Path $Destination 'toc.yml'
    $namespaces = Select-String -Path $toc -Pattern '^- name: (.+)$' |
        ForEach-Object { $_.Matches[0].Groups[1].Value } |
        Sort-Object

    $namespaceList = ($namespaces | ForEach-Object { "- [``$_``]($_.md)" }) -join "`n"

    $index = @"
# API reference

Generated from the XML documentation comments in ``src/GDK.Net`` by
[``eng/generate-docs.ps1``](../../eng/generate-docs.ps1). **Do not edit these files by hand** --
edit the doc comments and regenerate.

| | |
|---|---|
| GDK edition | ``$edition`` |
| Target framework | ``net10.0`` |
| Namespaces | $($namespaces.Count) |
| Pages | $pages |

## Scope

Two things are worth knowing about the scope of this reference.

**Internal interop is excluded.** docfx's default API filter emits only public and protected
members, so the ``GDK.Net.Interop`` layer -- the raw P/Invokes and the blittable native structs --
does not appear. That layer is ``internal`` and is not part of the supported surface. See
[``../architecture.md``](../architecture.md).

**Generated from ``net10.0``, and complete for all targets.** The projection multi-targets
``net8.0``, ``net10.0`` and ``netstandard2.0``. The ``#if NET7_0_OR_GREATER`` guards choose
``[UnmanagedCallersOnly]`` function pointers over ``Marshal.GetFunctionPointerForDelegate``, but
everything they switch is ``internal``: the three assemblies export the same public surface, so
nothing is missing from this reference. Nothing here is target-specific unless the page says so.

## Namespaces

$namespaceList

## Related

- [Getting started](../getting-started.md)
- [Architecture](../architecture.md)
- [Building](../building.md)
- [The pinned GDK edition](../gdk-edition.md)
"@

    $path = Join-Path $Destination 'README.md'
    [System.IO.File]::WriteAllText($path, ($index -replace "`r`n", "`n"), [System.Text.UTF8Encoding]::new($false))
}

Push-Location $repoRoot
try {
    if (-not $NoRestore) {
        dotnet tool restore
        if ($LASTEXITCODE -ne 0) {
            throw 'dotnet tool restore failed. docfx could not be resolved; see docs/building.md.'
        }
    }

    # docfx combines its --output base directory with the "dest" in docfx.json, which is "api".
    # So the base is docs/ normally, and a scratch directory for -Check.
    $outputBase = Join-Path $repoRoot 'docs'
    $generated = $committed
    $temporary = $null
    if ($Check) {
        $temporary = Join-Path ([System.IO.Path]::GetTempPath()) ("gdknet-docs-" + [guid]::NewGuid().ToString('N'))
        $outputBase = $temporary
        $generated = Join-Path $temporary 'api'
    }

    if (-not $Check -and (Test-Path $committed)) {
        # docfx does not prune pages for types that no longer exist.
        Remove-Item -Recurse -Force $committed
    }

    & dotnet docfx metadata $config --output $outputBase
    if ($LASTEXITCODE -ne 0) {
        throw "docfx metadata failed with exit code $LASTEXITCODE."
    }

    Write-ApiIndex -Destination $generated

    if (-not $Check) {
        $count = (Get-ChildItem $committed -File).Count
        Write-Host "docs/api: $count files regenerated."
        return
    }

    $expected = Get-ChildItem $generated -File | Sort-Object Name
    $actual = Get-ChildItem $committed -File -ErrorAction SilentlyContinue | Sort-Object Name

    $differences = [System.Collections.Generic.List[string]]::new()

    $expectedNames = $expected.Name
    $actualNames = if ($actual) { $actual.Name } else { @() }

    foreach ($name in $expectedNames) {
        if ($actualNames -notcontains $name) {
            $differences.Add("missing from docs/api: $name")
            continue
        }

        # Compared with line endings normalised: docfx writes LF, but a checkout
        # may have converted the committed copy to CRLF, and that is not drift.
        $left = (Get-Content (Join-Path $generated $name) -Raw) -replace "`r`n", "`n"
        $right = (Get-Content (Join-Path $committed $name) -Raw) -replace "`r`n", "`n"
        if ($left -ne $right) {
            $differences.Add("out of date: $name")
        }
    }

    foreach ($name in $actualNames) {
        if ($expectedNames -notcontains $name) {
            $differences.Add("stale, no longer generated: $name")
        }
    }

    Remove-Item -Recurse -Force $temporary -ErrorAction SilentlyContinue

    if ($differences.Count -gt 0) {
        Write-Host "docs/api is out of date. Run: pwsh eng/generate-docs.ps1" -ForegroundColor Red
        $differences | Select-Object -First 25 | ForEach-Object { Write-Host "  $_" }
        if ($differences.Count -gt 25) {
            Write-Host "  ... and $($differences.Count - 25) more"
        }
        exit 1
    }

    Write-Host "docs/api is up to date ($($expected.Count) files)."
}
finally {
    Pop-Location
}
